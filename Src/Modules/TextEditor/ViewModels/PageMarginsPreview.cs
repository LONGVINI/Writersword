namespace Writersword.Modules.TextEditor.ViewModels
{
    /// <summary>
    /// Поля страницы в ходе жеста на линейке — пока край тянут и до отпускания.
    ///
    /// Сами значения к этому моменту уже лежат в документе. Запись нужна как отдельное
    /// уведомление: на смену параметров страницы полотно пересобирает весь документ,
    /// а это на большом тексте секунды, и край шёл бы за мышью рывками. На жест же
    /// полотно перекладывает только видимые листы — текст идёт за краем сразу, как в
    /// Word. Полная пересборка случается один раз, после отпускания.
    /// </summary>
    public sealed record PageMarginsPreview(
        double TopMm,
        double BottomMm,
        double LeftMm,
        double RightMm);
}
