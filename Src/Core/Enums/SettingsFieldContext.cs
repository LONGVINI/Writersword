namespace Writersword.Core.Enums
{
    /// <summary>
    /// Контекст отображения поля настроек.
    /// Передаётся в SettingFieldControl чтобы определить
    /// какой набор кнопок рисовать рядом с полем.
    /// </summary>
    public enum SettingsFieldContext
    {
        /// <summary>
        /// Глобальная вкладка настроек модуля.
        /// Доступна кнопка сброса конкретного поля до хардкод дефолта.
        /// </summary>
        Global,

        /// <summary>
        /// Локальная вкладка настроек проекта.
        /// Доступны кнопки сброса поля до глобального значения
        /// и до хардкод дефолта.
        /// </summary>
        Local
    }
}