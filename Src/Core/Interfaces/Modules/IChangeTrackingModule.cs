using System;

namespace Writersword.Core.Interfaces.Modules
{
    /// <summary>
    /// Отметка состояния данных модуля.
    /// <para>
    /// History — состояние истории отмены: у каждой позиции в стеках Undo/Redo свой
    /// номер, и возврат по Ctrl+Z в ту же позицию возвращает тот же номер. Поэтому
    /// откат правок до сохранённого состояния снова делает модуль «сохранённым».
    /// </para>
    /// <para>
    /// Extra — счётчик правок, прошедших мимо истории отмены. Такую правку откатить
    /// нельзя, поэтому этот счётчик только растёт.
    /// </para>
    /// Две отметки равны тогда и только тогда, когда данные модуля в том же состоянии.
    /// </summary>
    public readonly record struct ModuleChangeStamp(long History, long Extra);

    /// <summary>
    /// Модуль сам сообщает о правках своих данных.
    /// <para>
    /// Раньше «есть ли несохранённое» выяснялось полным сбором данных модуля и
    /// сравнением хешей с файлом проекта — сотни мегабайт на каждое переключение
    /// вкладки и на каждый тик автосохранения. С отметками вопрос решается сравнением
    /// двух чисел, а сбор данных запускается, только когда данные действительно
    /// изменились с прошлой записи.
    /// </para>
    /// </summary>
    public interface IChangeTrackingModule
    {
        /// <summary>
        /// Модуль действительно отслеживает свои правки. false — модуль о правках не
        /// сообщает, и для вкладки с таким модулем работает прежний путь: полный сбор
        /// данных и сравнение с файлом.
        /// </summary>
        bool TracksChanges { get; }

        /// <summary>Текущая отметка состояния данных (см. ModuleChangeStamp).</summary>
        ModuleChangeStamp ChangeStamp { get; }

        /// <summary>
        /// Номер ревизии: растёт при любой правке, в том числе при Ctrl+Z, и никогда
        /// не возвращается назад. По нему решается, нужно ли снова писать кеш:
        /// совпадение ревизии гарантирует, что с прошлой записи ничего не менялось.
        /// </summary>
        long Revision { get; }

        /// <summary>
        /// Данные модуля изменились. Всегда поднимается на UI-потоке.
        /// </summary>
        event Action<IModule>? DataChanged;

        /// <summary>
        /// Текущее состояние модуля — загруженное, правок в нём нет. Вызывается вкладкой
        /// один раз, когда модуль получил свои данные и построил вью.
        /// <para>
        /// Загрузка сама порождает события «данные изменились»: модуль раскладывает
        /// полученные данные по своим коллекциям, вью при первом показе нормализует
        /// значения. Проверки этих событий отложены и без сброса срабатывали бы уже
        /// после того, как вкладка приняла исходное состояние, — вкладка с только что
        /// открытым проектом сразу считалась бы изменённой. Модуль отбрасывает такие
        /// отложенные проверки.
        /// </para>
        /// Только UI-поток.
        /// </summary>
        void AcceptLoadedState() { }
    }
}
