using System.Collections.Generic;
using System.Threading.Tasks;
using Writersword.Core.Models.Project;

namespace Writersword.Core.Interfaces.Modules
{
    /// <summary>
    /// Модуль, который держит файлы: картинки, шрифты, что угодно ещё.
    ///
    /// Проект передают другим людям, и передают его целиком — одним файлом. Всё,
    /// что видно на его страницах и карточках, обязано лежать внутри этого
    /// файла. Ссылка на картинку в папке автора у получателя не значит ничего:
    /// на её месте окажется пустое место, и объяснить его будет нечем.
    ///
    /// Слой проекта не знает, как устроены адреса файлов внутри модуля, и знать
    /// не должен: у картинок персонажей одна запись, у бумаги вида чтения
    /// другая. Он знает только три вопроса, и на них отвечает модуль.
    ///
    /// Реализуется по желанию: модуль без файлов этот интерфейс не объявляет, и
    /// слой проекта его просто не спрашивает.
    /// </summary>
    public interface IProjectAssetHolder
    {
        /// <summary>
        /// Все ссылки модуля на файлы — и живые, и те, что он держит как
        /// хранилище. Ничего не меняет: это ответ на вопрос «что у тебя есть».
        /// </summary>
        IEnumerable<ProjectAssetRef> CollectAssetRefs();

        /// <summary>
        /// Уложить в архив проекта всё, что лежит снаружи, и переписать свои
        /// ссылки на уложенное. Возвращает число уложенных файлов.
        ///
        /// Исходники при этом не трогаются: данные программы — библиотека, из
        /// которой берут, а не место, которое опустошают ради одного проекта.
        /// </summary>
        Task<int> EmbedExternalAssetsAsync();

        /// <summary>
        /// Убрать из архива файлы, на которые не осталось ни одной ссылки.
        ///
        /// Зовётся только по прямой просьбе человека. Уборка по таймеру уже
        /// пробовалась и была снята: она удаляла файл, который возвращался по
        /// Ctrl+Z или из версии восстановления. Поэтому живыми считаются не
        /// только ссылки текущего состояния, но и всё, откуда картинку ещё можно
        /// вернуть, — история отмены, кеш восстановления, буфер обмена.
        ///
        /// Файл, лежащий в наборе модуля (в паке аватарок, в подборке видов),
        /// мусором не считается никогда: набор собирают заранее и пользуются им
        /// потом, а ссылок на него может не быть вовсе.
        /// </summary>
        ProjectAssetCleanup CompactUnusedAssets();
    }
}
