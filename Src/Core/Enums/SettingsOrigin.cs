namespace Writersword.Core.Enums
{
    /// <summary>
    /// Источник текущего значения настройки.
    /// Используется в SettingValue для определения состояния поля
    /// и отображения соответствующих кнопок в SettingFieldControl.
    /// </summary>
    public enum SettingsOrigin
    {
        /// <summary>
        /// Значение совпадает с хардкод дефолтом.
        /// Кнопка сброса не отображается.
        /// </summary>
        Hardcoded,

        /// <summary>
        /// Значение установлено глобально и отличается от хардкода.
        /// В глобальной вкладке: показывает кнопку сброса до хардкода.
        /// В локальной вкладке: значение пришло из глобальных, локальный override не задан.
        /// </summary>
        Global,

        /// <summary>
        /// Значение переопределено локально для конкретного проекта.
        /// В локальной вкладке: показывает кнопки сброса до глобального и до хардкода.
        /// </summary>
        LocalOverride
    }
}