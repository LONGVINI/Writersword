namespace Writersword.Modules.Characters.Models.Enums
{
    /// <summary>
    /// Вид поля в карточке. Тип поля отвечает на вопрос «что хранится» —
    /// число, выбор, текст, — а вид на вопрос «как это показать». Одна и та же
    /// «Вспыльчивость» может быть шариками в одной анкете и полосой в другой, и
    /// значения при этом остаются сравнимыми: сравнивается число, а не картинка.
    ///
    /// Новые члены дописываются только в конец: перечисление сохраняется
    /// числом, и вставка в середину сменила бы вид уже настроенным полям.
    /// </summary>
    public enum CharacterFieldDisplay
    {
        /// <summary>
        /// Вид по умолчанию для типа: короткая шкала — шарики, длинная —
        /// полоса, выбор — чипы. У старых полей стоит именно он.
        /// </summary>
        Auto,

        /// <summary>Шарики: наведение подсвечивает, щелчок заполняет до выбранного.</summary>
        Balls,

        /// <summary>Полоса из делений — для шкал, где шариков было бы слишком много.</summary>
        Bar,

        /// <summary>Ползунок с подписью значения — для длинных и дробных шкал.</summary>
        Slider,

        /// <summary>
        /// Полюса: шкала между двумя крайностями, «интроверт — экстраверт».
        /// Отмечается одно положение, а не заполнение до него. Подписи полюсов —
        /// подписи краёв шкалы.
        /// </summary>
        Bipolar,

        /// <summary>Выбор чипами: все варианты на виду.</summary>
        Chips,

        /// <summary>Выбор выпадающим списком: для длинных списков вариантов.</summary>
        Dropdown
    }
}
