namespace Writersword.Core.Interfaces.Services.UI
{
    /// <summary>
    /// Показ снапшотов вкладок — мгновенное переключение в стиле браузера.
    /// Реализуется главным окном: при уходе с вкладки захватывается последний
    /// отрисованный кадр её док-области, при возврате этот кадр мгновенно
    /// показывается поверх контента, пока реальные модули прогружаются,
    /// и скрывается по их готовности. Пользователь видит вкладку «как была»
    /// сразу, независимо от того, выгружена она из памяти или нет.
    /// </summary>
    public interface ITabSnapshotPresenter
    {
        /// <summary>
        /// Захватить текущий кадр док-области для вкладки.
        /// Вызывать ДО приостановки вкладки — пока её вью прикреплены и отрисованы.
        /// </summary>
        /// <param name="tab">Вкладка-ключ снапшота</param>
        void CaptureTabSnapshot(object tab);

        /// <summary>
        /// Мгновенно показать сохранённый кадр вкладки поверх док-области.
        /// Кадр скрывается автоматически, когда реальный контент готов.
        /// Если снапшота для вкладки нет — ничего не происходит.
        /// </summary>
        /// <param name="tab">Вкладка-ключ снапшота</param>
        void ShowTabSnapshot(object tab);

        /// <summary>
        /// Удалить сохранённый кадр вкладки (закрытие вкладки) и освободить память.
        /// </summary>
        /// <param name="tab">Вкладка-ключ снапшота</param>
        void ForgetTabSnapshot(object tab);

        /// <summary>
        /// Показать поверх док-области оверлей «отпустите, чтобы открыть вкладку»
        /// с анимацией ожидания. Вызывается на старте перетаскивания вкладки:
        /// контент не трогается и не грузится, пока кнопка мыши не отпущена.
        /// </summary>
        void ShowTabDragPending();

        /// <summary>
        /// Скрыть оверлей ожидания отпускания вкладки.
        /// Вызывается при завершении перетаскивания — перед реальной активацией.
        /// </summary>
        void HideTabDragPending();
    }
}
