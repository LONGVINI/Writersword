namespace Writersword.Core.Models.Modules
{
    /// <summary>
    /// Состояние модуля для сохранения/восстановления
    /// Содержит данные двух типов: основные (CustomData) и сессионные (SessionData)
    /// </summary>
    public class ModuleState
    {
        /// <summary>
        /// Основные данные модуля (сохраняются в .writersword файл)
        /// Примеры: весь текст документа, список персонажей, полная статистика таймера
        /// МОЖЕТ БЫТЬ: строка, объект, словарь, массив - модуль сам решает структуру!
        /// </summary>
        public object? CustomData { get; set; }

        /// <summary>
        /// Рабочие данные сессии (сохраняются в .wsasd кеш)
        /// Примеры: позиция курсора, текущий запущенный таймер, открытый персонаж
        /// МОЖЕТ БЫТЬ: строка, объект, словарь - модуль сам решает структуру!
        /// Эти данные НЕ попадают в .writersword при сохранении
        /// </summary>
        public object? SessionData { get; set; }

        /// <summary>
        /// Позиция скролла (0.0 - 1.0)
        /// Универсальное свойство для всех модулей
        /// </summary>
        public double ScrollPosition { get; set; }
    }
}