namespace Writersword.Modules.Characters.Models.Enums
{
    /// <summary>
    /// Тип поля анкеты, он же тип значения у персонажа.
    ///
    /// Новые члены дописываются только в конец: в проекте перечисление
    /// сохранено числом, и вставка в середину переназначила бы типы уже
    /// заполненным полям — шкала стала бы текстом, текст выбором.
    /// </summary>
    public enum CharacterParameterType
    {
        /// <summary>Шкала с краями и шагом: кружочки, а для длинных — ползунок.</summary>
        Numeric,

        /// <summary>Короткий текст в одну строку: профессия, место рождения.</summary>
        Text,

        /// <summary>Один вариант из списка.</summary>
        StateList,

        /// <summary>Да или нет.</summary>
        Boolean,

        /// <summary>
        /// Свободное число без краёв: длина ушей, вес, год. От шкалы отличается
        /// тем, что мерой служит сама величина, а не «сколько из пяти».
        /// </summary>
        Number,

        /// <summary>
        /// Длинное описание в несколько абзацев. От короткого текста отличается
        /// только видом поля — и этого достаточно: в одну строку внешность не
        /// опишешь, а список коротких ответов не читается, когда каждый третий
        /// развёрнут на экран.
        /// </summary>
        LongText,

        /// <summary>Несколько вариантов из списка разом.</summary>
        MultiChoice
    }
}
