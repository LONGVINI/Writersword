namespace Writersword.Core.Interfaces.Services.Storage
{
    /// <summary>
    /// Хранилище секретов, которым не место в обычных настройках.
    ///
    /// Сейчас здесь живёт мастер-пароль синхронизации. Без него автоматическая
    /// отправка невозможна в принципе: каждая попытка упиралась бы в диалог
    /// ввода пароля, а автор в этот момент занят книгой, а не диалогами.
    ///
    /// Защита лежит на реализации и через неё на системе: на Windows это
    /// хранилище учётных данных, привязанное к учётной записи, на телефоне
    /// будет Keystore. Собственного шифрования здесь нет намеренно — ключ от
    /// него пришлось бы держать рядом, и защита свелась бы к запутыванию.
    /// </summary>
    public interface ISecretStore
    {
        /// <summary>Доступно ли хранилище на этой системе.</summary>
        bool IsAvailable { get; }

        /// <summary>Прочитать секрет или null, если его нет.</summary>
        string? Read(string key);

        /// <summary>Записать секрет, заменив прежний.</summary>
        bool Write(string key, string value);

        /// <summary>Удалить секрет. Отсутствие секрета ошибкой не считается.</summary>
        void Delete(string key);
    }
}
