using System.Collections.Generic;

namespace Writersword.Core.Models.Preview
{
    /// <summary>
    /// Плоский снимок сущности для показа чужим модулем. Модуль-владелец
    /// кладёт такой список рядом со своими данными при сохранении, а любой
    /// другой модуль читает его, ничего не зная о внутренней схеме владельца:
    /// редактор текста показывает карточку персонажа по ссылке, не разбирая
    /// формат модуля Characters.
    ///
    /// Формат общий для всех видов сущностей — персонаж, событие таймлайна,
    /// локация выглядят одинаково — и не меняется. Правки внутренней модели
    /// владельца не ломают тех, кто его читает.
    ///
    /// Снимок работает и когда модуля-владельца в сборке нет вовсе: данные
    /// в файле остаются, показать их по-прежнему есть чем.
    /// </summary>
    public class EntityPreview
    {
        /// <summary>Идентификатор сущности у владельца — цель ссылок.</summary>
        public string Id { get; set; } = string.Empty;

        /// <summary>Отображаемое имя.</summary>
        public string Title { get; set; } = string.Empty;

        /// <summary>Одна строка пояснения: короткое описание, роль, дата.</summary>
        public string Subtitle { get; set; } = string.Empty;

        /// <summary>Путь к картинке внутри проекта, если она есть.</summary>
        public string? Image { get; set; }

        /// <summary>Цвет сущности в формате #RRGGBB, если владелец его ведёт.</summary>
        public string? Color { get; set; }

        /// <summary>
        /// Короткие подписи состояний: «Мёртв», «Черновик», «Отменено».
        /// Только те, что владелец считает нужным показывать снаружи.
        /// </summary>
        public List<string> Badges { get; set; } = new();
    }
}
