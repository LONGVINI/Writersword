namespace Writersword.Modules.TextEditor.Models.Document
{
    /// <summary>
    /// Живое поле Word в строке текста: дата, время, номер страницы, число страниц.
    ///
    /// Значение такого поля не хранится в тексте — его показывает вёрстка: дата и
    /// время — на момент показа, как у Word при открытии документа; номер страницы —
    /// того листа, на котором стоит поле; число страниц — сколько их в документе.
    /// Поле стоит среди букв своего абзаца, как картинка в строке: лежит в
    /// <see cref="SectionModel.InlineObjects"/>, а run абзаца хранит ссылку на него и
    /// один символ-заполнитель. Для каретки, выделения и отмены поле — один знак;
    /// оформление его текста — оформление этого символа.
    ///
    /// Прочие поля Word (ссылки, нумерация подписей, условия) остаются в тексте своим
    /// последним значением, как раньше.
    /// </summary>
    public sealed class FieldBlock : BlockModel
    {
        public override BlockType BlockType => BlockType.Field;

        /// <summary>Код поля, как его пишет Word: DATE \@ "dd.MM.yyyy", PAGE, NUMPAGES.</summary>
        public string Instruction { get; set; } = string.Empty;

        /// <summary>
        /// Значение поля, сохранённое Word в файле. Показывается, пока своего значения
        /// у поля ещё нет (номер страницы до первой раскладки), и уходит в .docx у
        /// полей, которые считает раскладка.
        /// </summary>
        public string Result { get; set; } = string.Empty;
    }
}
