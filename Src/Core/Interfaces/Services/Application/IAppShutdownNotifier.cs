using System;

namespace Writersword.Core.Interfaces.Services
{
    /// <summary>
    /// Оповещение о ШТАТНОМ закрытии приложения.
    ///
    /// Приложение здесь только объявляет факт: «мы закрываемся полностью». Что при этом
    /// сделать — решает каждый модуль сам, в своём коде и по своим правилам. Обратной
    /// зависимости нет: ядро и приложение о модулях ничего не знают.
    ///
    /// Событие поднимается ТОЛЬКО при закрытии по воле пользователя. Падение, убийство
    /// процесса и любое аварийное завершение сюда не приходят намеренно: кеш
    /// восстановления обязан пережить их нетронутым.
    ///
    /// Обработчики выполняются синхронно, в момент закрытия, и должны быть короткими:
    /// после выхода из них приложение завершается. Исключение одного обработчика не
    /// должно мешать остальным — источник события их изолирует.
    /// </summary>
    public interface IAppShutdownNotifier
    {
        /// <summary>
        /// Приложение закрывается штатно. Подписка — на всё время жизни модуля,
        /// отписка — в его Dispose.
        /// </summary>
        event Action? GracefulShutdown;

        /// <summary>
        /// Объявить штатное закрытие. Вызывает только приложение, из обработчика
        /// закрытия главного окна.
        /// </summary>
        void NotifyGracefulShutdown();
    }
}
