namespace Writersword
{
    public static class AppConstants
    {
        /// <summary>
        /// Версия программы. Одно место, откуда её берут все остальные:
        /// заголовки, точки восстановления, отчёты об ошибках.
        ///
        /// В точках восстановления она нужна затем, что формат проекта со
        /// временем меняется. Через год, разбирая старую историю, по одной
        /// дате не понять, какой версией снята точка и чем её открывать.
        /// </summary>
        public const string Version = "0.1.0";

        /// <summary>
        /// Версия в виде, пригодном для имени файла.
        ///
        /// Двоеточие, с которым версия пишется в коммитах, Windows в именах
        /// файлов не допускает, поэтому здесь только буква и цифры.
        /// </summary>
        public const string VersionTag = "v" + Version;
    }
}
