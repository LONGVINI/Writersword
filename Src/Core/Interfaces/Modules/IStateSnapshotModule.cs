namespace Writersword.Core.Interfaces.Modules
{
    /// <summary>
    /// Модуль с тяжёлой сериализацией состояния, поддерживающий двухфазный сбор данных.
    /// Фаза 1 — быстрый снимок состояния на UI-потоке (TakeStateSnapshot):
    /// копирование модели в памяти без JSON-сериализации.
    /// Фаза 2 — тяжёлая сериализация снимка (SerializeStateSnapshot) на любом потоке.
    /// Позволяет собирать данные модуля без длительной блокировки UI-потока:
    /// вызывающий код снимает снимок на UI-потоке за миллисекунды и уводит
    /// сериализацию в фоновую задачу.
    /// </summary>
    public interface IStateSnapshotModule
    {
        /// <summary>
        /// Снять быстрый снимок состояния модуля.
        /// Требует UI-поток — реализация сама выполняет переход если вызвана с другого потока.
        /// Возвращает null в тех же случаях, когда GetCustomData вернул бы null
        /// (модулю нечего сохранять или произошла ошибка).
        /// </summary>
        /// <returns>Непрозрачный объект-снимок или null</returns>
        object? TakeStateSnapshot();

        /// <summary>
        /// Сериализовать снимок в формат данных GetCustomData.
        /// Можно вызывать с любого потока — снимок изолирован от живой модели.
        /// Результат идентичен результату GetCustomData() на момент снятия снимка.
        /// </summary>
        /// <param name="snapshot">Снимок полученный из TakeStateSnapshot</param>
        /// <returns>Данные модуля в формате GetCustomData или null при ошибке</returns>
        object? SerializeStateSnapshot(object snapshot);
    }
}
