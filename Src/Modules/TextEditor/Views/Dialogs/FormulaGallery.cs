    /// <summary>Заготовка формулы: запись командами LaTeX и подсказка.</summary>
    /// <param name="Latex">
    /// Запись. Пустые фигурные скобки {} и квадратные [] — пустые места: в окне на
    /// их месте пунктирный квадратик, каретка встаёт в первое, Tab ведёт к следующему.
    /// </param>
    /// <param name="Tip">Подсказка при наведении.</param>
    public sealed record FormulaTemplate(string Latex, string Tip);

    /// <summary>Раздел галереи конструкции: подзаголовок и заготовки.</summary>
    public sealed record FormulaTemplateSection(string Title, IReadOnlyList<FormulaTemplate> Items);

    /// <summary>Конструкция ленты формулы: подпись, образец на кнопке и галерея заготовок.</summary>
    public sealed record FormulaStructure(string Title, string IconLatex, IReadOnlyList<FormulaTemplateSection> Sections);

    /// <summary>Набор знаков ленты формулы.</summary>
    /// <param name="Title">Название набора.</param>
    /// <param name="Symbols">Знак и его запись: команда LaTeX или сам знак.</param>
    public sealed record FormulaSymbolSet(string Title, IReadOnlyList<(string Symbol, string Insert, string Tip)> Symbols);

