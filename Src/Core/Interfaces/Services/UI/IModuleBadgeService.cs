namespace Writersword.Core.Interfaces.Services.UI
{
    /// <summary>
    /// Пометки на вкладке модуля: красный значок рядом с названием и пояснение
    /// по наведению.
    ///
    /// Нужен потому, что модуль до своей вкладки дотянуться сам не может.
    /// Вкладками ведает Dock, а он живёт в сборке приложения, на которую модули
    /// не ссылаются и ссылаться не должны — вышла бы кольцевая зависимость.
    /// Поэтому здесь только намерение «показать вот это», а как именно оно
    /// нарисуется, знает приложение.
    ///
    /// Всплывающее уведомление и значок решают разные задачи и не заменяют друг
    /// друга: сообщение говорит один раз и исчезает, значок остаётся, пока
    /// причина не устранена.
    /// </summary>
    public interface IModuleBadgeService
    {
        /// <summary>
        /// Показать или снять предупреждение на вкладке модуля.
        ///
        /// Пустой текст снимает значок. Снимать нужно так же явно, как ставить:
        /// вкладка переживает смену документа, и оставшийся от прошлого значок
        /// врал бы про нынешний.
        ///
        /// Если вкладки в раскладке нет — модуль закрыт или ещё не прикреплён, —
        /// вызов молча ничего не делает: показывать негде, и это не ошибка.
        /// </summary>
        /// <param name="moduleType">Ключ модуля, как в IModule.moduleType.</param>
        /// <param name="text">Текст подсказки или null, чтобы снять значок.</param>
        void SetWarning(string moduleType, string? text);
    }
}
